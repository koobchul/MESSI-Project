import argparse

import jax
import jax.numpy as jnp
import numpy as np

from project.algorithms.rollout_jit import (
    initialize_jit_rollout_carry,
    make_jitted_rollout_collector,
)
from project.envs.critic_encoder import encode_critic_state
from project.envs.messi_5v5 import make_5v5_env, reset_5v5_env
from project.envs.obs_encoder import encode_mlp_observation
from project.models.action_head import HybridActionHead
from project.models.critic import CentralizedCritic
from project.models.mlp_actor import MLPActorBackbone
from project.utils.checkpoint import load_checkpoint


INTENT_NAMES = [
    "MOVE",
    "CONTROL",
    "PASS",
    "SHOT",
    "CLEAR",
    "CHALLENGE",
]

CONTINUOUS_NAMES = [
    "move_x",
    "move_y",
    "force_ball_x",
    "force_ball_y",
    "launch",
    "spin_x",
    "spin_y",
]


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Compare two frozen MLP actors on exactly the same "
            "observation states generated by a reference policy."
        )
    )
    parser.add_argument("--reference-checkpoint", type=str, required=True)
    parser.add_argument("--comparison-checkpoint", type=str, required=True)
    parser.add_argument("--num-steps", type=int, default=6400)
    parser.add_argument("--rollout-length", type=int, default=128)
    parser.add_argument("--seed", type=int, default=1000)
    return parser.parse_args()


def initialize_models(env, reset):
    roster = env.roster_metadata(reset.rollout)
    obs = env.observe_all(reset.rollout)
    actor_obs = encode_mlp_observation(obs, roster)

    backbone = MLPActorBackbone(hidden_dim=256)
    backbone_variables = backbone.init(jax.random.key(1), actor_obs)
    latent = backbone.apply(backbone_variables, actor_obs)

    action_head = HybridActionHead()
    action_head.init(jax.random.key(2), latent)

    global_state = env.global_state_view(reset.rollout)
    critic_obs = encode_critic_state(global_state, controlled_team=0)

    critic = CentralizedCritic(hidden_dim=256)
    critic.init(jax.random.key(3), critic_obs[None, :])

    return backbone, action_head, critic


def main():
    args = parse_args()

    if args.num_steps <= 0:
        raise ValueError("--num-steps must be > 0.")
    if args.rollout_length <= 0:
        raise ValueError("--rollout-length must be > 0.")
    if args.num_steps % args.rollout_length != 0:
        raise ValueError(
            "--num-steps must be divisible by --rollout-length for this diagnostic."
        )

    reference_checkpoint = load_checkpoint(args.reference_checkpoint)
    comparison_checkpoint = load_checkpoint(args.comparison_checkpoint)

    reference_actor_params = jax.device_put(reference_checkpoint["actor_params"])
    reference_critic_params = jax.device_put(reference_checkpoint["critic_params"])
    comparison_actor_params = jax.device_put(comparison_checkpoint["actor_params"])

    env, initial_reset = make_5v5_env(seed=args.seed)
    backbone, action_head, critic = initialize_models(env, initial_reset)

    controlled_indices = jnp.array([0, 1, 2, 3, 4], dtype=jnp.int32)

    collector = make_jitted_rollout_collector(
        env=env,
        backbone=backbone,
        action_head=action_head,
        critic=critic,
        rollout_length=args.rollout_length,
        controlled_indices=controlled_indices,
        controlled_team=0,
    )

    reset = reset_5v5_env(env, seed=args.seed)
    setup = reset.setup
    roster = env.roster_metadata(reset.rollout)
    si_roster = env.roster_metadata_si(reset.rollout)

    opponent_base_key = jax.random.key(args.seed + 10000)
    rollout_base_key = jax.random.key(args.seed + 20000)
    opponent_key = jax.random.fold_in(opponent_base_key, 0)
    rollout_key = jax.random.fold_in(rollout_base_key, 0)

    carry = initialize_jit_rollout_carry(
        env=env,
        reset=reset,
        opponent_key=opponent_key,
    )

    @jax.jit
    def get_actor_output(params, actor_obs):
        latent = backbone.apply(
            {"params": params["backbone"]},
            actor_obs,
        )
        return action_head.apply(
            {"params": params["head"]},
            latent,
        )

    reference_prob_chunks = []
    comparison_prob_chunks = []
    reference_mean_chunks = []
    comparison_mean_chunks = []
    reference_std_chunks = []
    comparison_std_chunks = []

    num_chunks = args.num_steps // args.rollout_length
    valid_transition_count = 0

    print("\n========================================")
    print("MESSI Same-State Actor Comparison")
    print("========================================")
    print("reference:", args.reference_checkpoint)
    print("comparison:", args.comparison_checkpoint)
    print("seed:", args.seed)
    print("requested steps:", args.num_steps)
    print("rollout length:", args.rollout_length)

    for chunk_index in range(num_chunks):
        batch, valid_mask, carry = collector(
            setup,
            carry,
            roster,
            si_roster,
            reference_actor_params,
            reference_critic_params,
            rollout_key,
        )

        jax.block_until_ready(carry.rollout.state.control_tick)

        reference_output = get_actor_output(reference_actor_params, batch.actor_obs)
        comparison_output = get_actor_output(comparison_actor_params, batch.actor_obs)
        jax.block_until_ready(comparison_output.intent_logits)

        valid = np.asarray(jax.device_get(valid_mask)).astype(bool)

        reference_probs = np.asarray(
            jax.device_get(jax.nn.softmax(reference_output.intent_logits, axis=-1))
        )
        comparison_probs = np.asarray(
            jax.device_get(jax.nn.softmax(comparison_output.intent_logits, axis=-1))
        )
        reference_means = np.asarray(
            jax.device_get(reference_output.continuous_mean)
        )
        comparison_means = np.asarray(
            jax.device_get(comparison_output.continuous_mean)
        )
        reference_stds = np.asarray(
            jax.device_get(jnp.exp(reference_output.continuous_log_std))
        )
        comparison_stds = np.asarray(
            jax.device_get(jnp.exp(comparison_output.continuous_log_std))
        )

        if np.any(valid):
            reference_prob_chunks.append(
                reference_probs[valid].reshape(-1, len(INTENT_NAMES))
            )
            comparison_prob_chunks.append(
                comparison_probs[valid].reshape(-1, len(INTENT_NAMES))
            )
            reference_mean_chunks.append(
                reference_means[valid].reshape(-1, len(CONTINUOUS_NAMES))
            )
            comparison_mean_chunks.append(
                comparison_means[valid].reshape(-1, len(CONTINUOUS_NAMES))
            )
            reference_std_chunks.append(
                reference_stds[valid].reshape(-1, len(CONTINUOUS_NAMES))
            )
            comparison_std_chunks.append(
                comparison_stds[valid].reshape(-1, len(CONTINUOUS_NAMES))
            )
            valid_transition_count += int(np.sum(valid))

        if (chunk_index + 1) % 10 == 0 or chunk_index == num_chunks - 1:
            score = np.asarray(jax.device_get(carry.rollout.state.score))
            print(
                f"chunk={chunk_index + 1}/{num_chunks}"
                f" | valid_steps={valid_transition_count}"
                f" | reference_score={int(score[0])}-{int(score[1])}"
            )

        if bool(jax.device_get(carry.done)):
            print("reference rollout ended before the requested fixed horizon.")
            break

    if not reference_prob_chunks:
        raise RuntimeError("No valid actor observations were collected.")

    reference_probs = np.concatenate(reference_prob_chunks, axis=0)
    comparison_probs = np.concatenate(comparison_prob_chunks, axis=0)
    reference_means = np.concatenate(reference_mean_chunks, axis=0)
    comparison_means = np.concatenate(comparison_mean_chunks, axis=0)
    reference_stds = np.concatenate(reference_std_chunks, axis=0)
    comparison_stds = np.concatenate(comparison_std_chunks, axis=0)

    print("\n========================================")
    print("SAME-STATE RESULTS")
    print("========================================")
    print("valid environment transitions:", valid_transition_count)
    print("controlled-player observations:", reference_probs.shape[0])

    reference_argmax = np.argmax(reference_probs, axis=-1)
    comparison_argmax = np.argmax(comparison_probs, axis=-1)
    argmax_disagreement = np.mean(reference_argmax != comparison_argmax)
    total_variation = 0.5 * np.sum(
        np.abs(comparison_probs - reference_probs), axis=-1
    )

    print("\n--- Discrete Intent Policy ---")
    print("argmax disagreement:", f"{100.0 * argmax_disagreement:.2f}%")
    print("mean total-variation distance:", f"{np.mean(total_variation):.6f}")
    print("median total-variation distance:", f"{np.median(total_variation):.6f}")
    print(
        "95th percentile TV distance:",
        f"{np.percentile(total_variation, 95):.6f}",
    )

    print(
        "\nIntent"
        f"{'Reference %':>15}"
        f"{'Comparison %':>15}"
        f"{'Delta pp':>12}"
    )

    reference_mean_probs = np.mean(reference_probs, axis=0)
    comparison_mean_probs = np.mean(comparison_probs, axis=0)

    for index, name in enumerate(INTENT_NAMES):
        reference_percent = 100.0 * reference_mean_probs[index]
        comparison_percent = 100.0 * comparison_mean_probs[index]
        print(
            f"{name:<12}"
            f"{reference_percent:>15.3f}"
            f"{comparison_percent:>15.3f}"
            f"{comparison_percent - reference_percent:>12.3f}"
        )

    continuous_delta = comparison_means - reference_means

    print("\n--- Continuous Mean Policy ---")
    print(
        f"{'Dimension':<16}"
        f"{'RefMean':>10}"
        f"{'CmpMean':>10}"
        f"{'Delta':>10}"
        f"{'MAE':>10}"
        f"{'RMSE':>10}"
        f"{'RefStd':>10}"
        f"{'CmpStd':>10}"
    )

    for index, name in enumerate(CONTINUOUS_NAMES):
        delta = continuous_delta[:, index]
        print(
            f"{name:<16}"
            f"{np.mean(reference_means[:, index]):>10.4f}"
            f"{np.mean(comparison_means[:, index]):>10.4f}"
            f"{np.mean(delta):>10.4f}"
            f"{np.mean(np.abs(delta)):>10.4f}"
            f"{np.sqrt(np.mean(delta ** 2)):>10.4f}"
            f"{np.mean(reference_stds[:, index]):>10.4f}"
            f"{np.mean(comparison_stds[:, index]):>10.4f}"
        )

    per_sample_continuous_l2 = np.linalg.norm(continuous_delta, axis=-1)

    print("\nContinuous-mean L2 distance:")
    print("  mean:", f"{np.mean(per_sample_continuous_l2):.6f}")
    print("  median:", f"{np.median(per_sample_continuous_l2):.6f}")
    print(
        "  95th percentile:",
        f"{np.percentile(per_sample_continuous_l2, 95):.6f}",
    )

    final_score = np.asarray(jax.device_get(carry.rollout.state.score))
    print(
        "\nReference rollout score:",
        f"{int(final_score[0])}-{int(final_score[1])}",
    )

    print("\nInterpretation:")
    print(
        "Both policies above were evaluated on the exact same actor observations."
    )
    print(
        "Therefore the reported policy-output differences are not caused by "
        "different state visitation in this comparison."
    )


if __name__ == "__main__":
    main()
